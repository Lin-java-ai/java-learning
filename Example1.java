package demo.cycle;

public class Example1 {
    /**
     * 注释
     * @param args
     */
    public static void main(String[] args) {
        //定义两个整数变量a和b
        int a = 5; // 单行注释：这里定义了变量a并初始化为5
        int b = 10;// 多行注释:这里定义了变量b并初始化为10

        //计算a和b的和，并将结果储存在sum中
        int sum = a + b;
        System.out.println(sum);
    }
}
